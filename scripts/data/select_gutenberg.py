#!/usr/bin/env python3
"""Write a list of Project Gutenberg books to download.

The list is chosen from the official offline catalog (pg_catalog.csv), so
the selection is reproducible from the seed and documented by title.

  # the curated list used for correctness runs (explicit ids)
  select_gutenberg.py --ids 1342,84,11 --out data/lists/classics-60.txt

  # a seeded random sample of English texts, e.g. the base corpus for scaling
  select_gutenberg.py --count 2000 --seed 452 --out data/lists/sample-2000.txt
"""

import argparse
import csv
import os
import random
import sys
import urllib.request

from dslib import read_id_list

CATALOG_URL = "https://www.gutenberg.org/cache/epub/feeds/pg_catalog.csv"
USER_AGENT = "cs452-spark-connect-go-datasets/1.0"


def load_catalog(path):
    if not os.path.exists(path):
        print(f"downloading {CATALOG_URL} -> {path}", file=sys.stderr)
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        req = urllib.request.Request(CATALOG_URL, headers={"User-Agent": USER_AGENT})
        with urllib.request.urlopen(req, timeout=120) as resp, open(path + ".tmp", "wb") as out:
            out.write(resp.read())
        os.replace(path + ".tmp", path)
    with open(path, encoding="utf-8", newline="") as f:
        return {int(row["Text#"]): row for row in csv.DictReader(f)}


def describe(row):
    title = " ".join(row["Title"].split())
    author = row["Authors"].split(";")[0].strip()
    return f"{title[:70]} / {author[:40]}" if author else title[:70]


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = p.add_mutually_exclusive_group(required=True)
    group.add_argument("--ids", help="comma-separated book ids to list as is")
    group.add_argument("--count", type=int, help="number of books to sample")
    p.add_argument("--seed", type=int, default=452, help="random seed for --count (default 452)")
    p.add_argument("--language", default="en", help="catalog language code (default en)")
    p.add_argument("--exclude", action="append", default=[], help="list file whose books must not be sampled")
    p.add_argument("--catalog", default="data/raw/pg_catalog.csv", help="catalog cache (downloaded if missing)")
    p.add_argument("--out", required=True, help="list file to write")
    args = p.parse_args()

    catalog = load_catalog(args.catalog)
    if args.ids:
        ids = [int(x) for x in args.ids.split(",") if x.strip()]
        missing = [i for i in ids if i not in catalog]
        if missing:
            sys.exit(f"not in the catalog: {missing}")
        header = "explicit selection"
    else:
        excluded = set()
        for path in args.exclude:
            excluded.update(read_id_list(path))
        candidates = sorted(
            i for i, row in catalog.items()
            if row["Type"] == "Text" and row["Language"] == args.language and i not in excluded
        )
        if args.count > len(candidates):
            sys.exit(f"only {len(candidates)} candidate books")
        ids = sorted(random.Random(args.seed).sample(candidates, args.count))
        header = (f"{args.count} random '{args.language}' texts out of {len(candidates)} "
                  f"(seed {args.seed}, catalog {os.path.basename(args.catalog)})")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(f"# Project Gutenberg books: {header}\n")
        f.write("# generated by scripts/data/select_gutenberg.py; format: <id>  # <title> / <first author>\n")
        for i in ids:
            f.write(f"{i}  # {describe(catalog[i])}\n")
    print(f"wrote {len(ids)} ids to {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
