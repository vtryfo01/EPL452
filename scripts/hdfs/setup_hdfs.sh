#!/usr/bin/env bash
# Install, configure and start HDFS on one node of the cluster.
#
#   setup_hdfs.sh namenode <namenode-host>   # on the master node
#   setup_hdfs.sh datanode <namenode-host>   # on every worker node
#   setup_hdfs.sh both     <namenode-host>   # single-node HDFS for local tests
#
# <namenode-host> is the master's name or IP on the experiment LAN (node0 in
# the CloudLab profile), so that HDFS traffic stays on that network. Run the
# script as the normal experiment user (with sudo rights); the daemons run as
# that user. It is idempotent: re-running it rewrites the configuration and
# starts any daemon that is not running. The NameNode is formatted only once.
#
# Settings (environment variables, defaults in brackets):
#   HADOOP_VERSION    Hadoop release to install [3.4.3]
#   HADOOP_HOME       install directory [/opt/hadoop]
#   HADOOP_TARBALL    install from this local tarball instead of downloading
#   HDFS_DATA_ROOT    metadata, blocks, logs [/mydata/hdfs]; on CloudLab this
#                     should be the large extra filesystem, not the small root disk
#   HDFS_REPLICATION  block replication [2]
#   HDFS_BLOCK_SIZE   block size [128m], matches the dataset part files
#   HDFS_PORT         NameNode RPC port [9000]
#   HDFS_JAVA_HOME    JDK used by the daemons [OpenJDK 11, installed if missing].
#                     Hadoop 3.4 supports Java 8/11 at runtime; Spark 4 keeps
#                     its own Java 17 through its own JAVA_HOME.
set -euo pipefail

usage() { sed -n '2,6p' "$0" | sed 's/^# \{0,1\}//'; exit 2; }
log() { echo "setup_hdfs: $*" >&2; }
die() { log "error: $*"; exit 1; }

ROLE=${1:-}
NAMENODE=${2:-}
[[ $ROLE =~ ^(namenode|datanode|both)$ && -n $NAMENODE ]] || usage
[[ $EUID -ne 0 ]] || die "run as the experiment user, not root (the HDFS daemons must not run as root)"

HADOOP_VERSION=${HADOOP_VERSION:-3.4.3}
HADOOP_HOME=${HADOOP_HOME:-/opt/hadoop}
HDFS_DATA_ROOT=${HDFS_DATA_ROOT:-/mydata/hdfs}
HDFS_REPLICATION=${HDFS_REPLICATION:-2}
HDFS_BLOCK_SIZE=${HDFS_BLOCK_SIZE:-128m}
HDFS_PORT=${HDFS_PORT:-9000}
ARCH=$(dpkg --print-architecture 2>/dev/null || echo amd64)
HDFS_JAVA_HOME=${HDFS_JAVA_HOME:-/usr/lib/jvm/java-11-openjdk-$ARCH}
CONF=$HADOOP_HOME/etc/hadoop
ME=$(id -un)

as_root() { sudo -n "$@"; }

# make_dir creates a directory owned by the current user, using sudo if needed.
make_dir() {
  mkdir -p "$1" 2>/dev/null || as_root mkdir -p "$1" || die "cannot create $1"
  [[ -w $1 ]] || as_root chown -R "$ME:" "$1" || die "cannot write to $1"
}

install_java() {
  [[ -x $HDFS_JAVA_HOME/bin/java ]] && return
  log "installing OpenJDK 11 for HDFS"
  as_root apt-get update -q
  as_root env DEBIAN_FRONTEND=noninteractive apt-get install -y -q openjdk-11-jre-headless
  [[ -x $HDFS_JAVA_HOME/bin/java ]] || die "no Java at $HDFS_JAVA_HOME; set HDFS_JAVA_HOME"
}

install_hadoop() {
  if [[ -x $HADOOP_HOME/bin/hdfs ]]; then
    log "Hadoop already installed in $HADOOP_HOME"
    return
  fi
  local name=hadoop-$HADOOP_VERSION suffix="" tarball=${HADOOP_TARBALL:-}
  [[ $ARCH == arm64 ]] && suffix=-aarch64
  if [[ -z $tarball ]]; then
    tarball=/tmp/$name$suffix.tar.gz
    if [[ ! -s $tarball ]]; then
      for mirror in https://dlcdn.apache.org/hadoop/common https://archive.apache.org/dist/hadoop/common; do
        log "downloading $mirror/$name/$name$suffix.tar.gz"
        if curl -fsSL -o "$tarball.part" "$mirror/$name/$name$suffix.tar.gz"; then
          mv "$tarball.part" "$tarball"
          break
        fi
      done
      [[ -s $tarball ]] || die "could not download Hadoop $HADOOP_VERSION"
    fi
  fi
  make_dir "$HADOOP_HOME"
  log "unpacking $tarball into $HADOOP_HOME"
  tar -xzf "$tarball" -C "$HADOOP_HOME" --strip-components=1
}

write_config() {
  # DataNodes report their LAN address, the name Spark uses for its executors,
  # otherwise Spark cannot schedule tasks next to their blocks.
  local nn_ip local_ip
  nn_ip=$(getent ahostsv4 "$NAMENODE" | awk 'NR == 1 {print $1}')
  local_ip=$(ip -4 -o route get "$nn_ip" | sed -E 's/.* src ([0-9.]+).*/\1/')

  make_dir "$HDFS_DATA_ROOT"
  mkdir -p "$HDFS_DATA_ROOT"/{name,data,logs,pids,tmp}

  cat > "$CONF/core-site.xml" <<EOF
<?xml version="1.0"?>
<!-- Generated by scripts/hdfs/setup_hdfs.sh -->
<configuration>
  <property><name>fs.defaultFS</name><value>hdfs://$NAMENODE:$HDFS_PORT</value></property>
  <property><name>hadoop.tmp.dir</name><value>$HDFS_DATA_ROOT/tmp</value></property>
</configuration>
EOF

  cat > "$CONF/hdfs-site.xml" <<EOF
<?xml version="1.0"?>
<!-- Generated by scripts/hdfs/setup_hdfs.sh -->
<configuration>
  <property><name>dfs.replication</name><value>$HDFS_REPLICATION</value></property>
  <property><name>dfs.blocksize</name><value>$HDFS_BLOCK_SIZE</value></property>
  <property><name>dfs.namenode.name.dir</name><value>file://$HDFS_DATA_ROOT/name</value></property>
  <property><name>dfs.datanode.data.dir</name><value>file://$HDFS_DATA_ROOT/data</value></property>
  <property><name>dfs.datanode.hostname</name><value>$local_ip</value></property>
  <!-- Listen on every interface; clients reach the NameNode through $NAMENODE. -->
  <property><name>dfs.namenode.rpc-bind-host</name><value>0.0.0.0</value></property>
  <property><name>dfs.namenode.http-bind-host</name><value>0.0.0.0</value></property>
  <!-- CloudLab LAN addresses have no reverse DNS entries. -->
  <property><name>dfs.namenode.datanode.registration.ip-hostname-check</name><value>false</value></property>
  <!-- Course cluster: the Spark Connect server may run as another user than the loader. -->
  <property><name>dfs.permissions.enabled</name><value>false</value></property>
</configuration>
EOF

  # Keep the distribution's hadoop-env.sh and append our settings to a copy.
  [[ -f $CONF/hadoop-env.sh.orig ]] || cp "$CONF/hadoop-env.sh" "$CONF/hadoop-env.sh.orig"
  {
    cat "$CONF/hadoop-env.sh.orig"
    echo "# Added by scripts/hdfs/setup_hdfs.sh"
    echo "export JAVA_HOME=$HDFS_JAVA_HOME"
    echo "export HADOOP_LOG_DIR=$HDFS_DATA_ROOT/logs"
    echo "export HADOOP_PID_DIR=$HDFS_DATA_ROOT/pids"
  } > "$CONF/hadoop-env.sh"

  # Put hdfs on the PATH of login shells (optional: needs sudo).
  local profile="export HADOOP_HOME=$HADOOP_HOME
export HADOOP_CONF_DIR=$CONF
export PATH=\$PATH:$HADOOP_HOME/bin"
  if ! echo "$profile" | as_root tee /etc/profile.d/hadoop.sh >/dev/null 2>&1; then
    log "note: could not write /etc/profile.d/hadoop.sh; use $HADOOP_HOME/bin/hdfs"
  fi
}

hdfs() { "$HADOOP_HOME/bin/hdfs" "$@"; }

# daemon_running checks the pid file written by "hdfs --daemon start"
# ("hdfs --daemon status" exits 0 even when the daemon is stopped).
daemon_running() {
  local pidfile=$HDFS_DATA_ROOT/pids/hadoop-$ME-$1.pid
  [[ -f $pidfile ]] && kill -0 "$(cat "$pidfile")" 2>/dev/null
}

start_daemon() {
  if daemon_running "$1"; then
    log "$1 already running"
    return
  fi
  log "starting $1"
  hdfs --daemon start "$1"
  sleep 3
  daemon_running "$1" || die "$1 exited, see $HDFS_DATA_ROOT/logs/hadoop-$ME-$1-$(hostname).log"
}

start_namenode() {
  local fresh=false state=""
  if [[ ! -f $HDFS_DATA_ROOT/name/current/VERSION ]]; then
    log "formatting the NameNode"
    hdfs namenode -format -nonInteractive -clusterid cs452 2>"$HDFS_DATA_ROOT/logs/format.log" ||
      die "format failed, see $HDFS_DATA_ROOT/logs/format.log"
    fresh=true
  fi
  start_daemon namenode
  # The RPC port opens a few seconds after the process starts.
  for _ in $(seq 30); do
    state=$(hdfs dfsadmin -safemode get 2>/dev/null) && break
    sleep 2
  done
  [[ -n $state ]] || die "the NameNode is not answering on $NAMENODE:$HDFS_PORT, see $HDFS_DATA_ROOT/logs"
  log "NameNode up: $state"
  # A restarted NameNode stays in safe mode until the DataNodes report their
  # blocks, so only a new (empty) file system is initialized here;
  # check_hdfs.sh waits for safe mode to end.
  if $fresh; then
    timeout 60 "$HADOOP_HOME/bin/hdfs" dfsadmin -safemode wait >/dev/null
    hdfs dfs -mkdir -p /datasets /results
  fi
}

install_java
install_hadoop
write_config
case $ROLE in
  namenode) start_namenode ;;
  datanode) start_daemon datanode ;;
  both) start_namenode; start_daemon datanode ;;
esac
log "done: $ROLE on $(hostname), fs.defaultFS=hdfs://$NAMENODE:$HDFS_PORT"
